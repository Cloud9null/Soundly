"""Generate copyright-free deterministic FLAC fixtures; ffmpeg is a test-generation tool only."""
from pathlib import Path
import base64,hashlib,struct,subprocess,tempfile
root=Path(__file__).resolve().parent.parent
out=['// Generated by Scripts/generate_audio_fixtures.py. No third-party music.','// '+subprocess.check_output(['ffmpeg','-version'],text=True).splitlines()[0],'enum FLACFixtures {']
for bits,rate in [(16,44100),(24,96000)]:
    scale=1 << (bits-1)
    raw=b''.join(int(v*scale).to_bytes(bits//8,'little',signed=True) for i in range(2048) for v in ([.25,-.375] if i%2==0 else [-.125,.0625]))
    with tempfile.TemporaryDirectory() as tmp:
        target=Path(tmp)/'reference.flac'
        args=['ffmpeg','-v','error','-f',f's{bits}le','-ar',str(rate),'-ac','2','-i','pipe:0','-c:a','flac','-sample_fmt','s16' if bits==16 else 's32']
        if bits==24: args+=['-bits_per_raw_sample','24']
        subprocess.run(args+['-metadata_header_padding','0',str(target)],input=raw,check=True)
        decoded=subprocess.check_output(['ffmpeg','-v','error','-i',str(target),'-f',f's{bits}le','-acodec',f'pcm_s{bits}le','pipe:1'])
        assert decoded==raw, 'Encoded FLAC failed source PCM comparison'
        out += [f'    // Original/decoded interleaved signed little-endian PCM SHA-256: {hashlib.sha256(raw).hexdigest()}', f'    static let pcm{bits} = "{base64.b64encode(target.read_bytes()).decode()}"']
out+=['}']
(root/'iOSTests/FLACFixtures.swift').write_text('\n'.join(out)+'\n')
